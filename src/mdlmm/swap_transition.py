"""LO swap state model checked against the D1-bound deployed program binary.

This is a separate transition result, never the quote-only SDK result. Its
rules are tested against raw pre/post accounts and CPI events generated by
local execution of binary d296c677... at explicit synthetic states. Historical
prestate, instruction coverage, and runtime feature equivalence remain separate
requirements; existing historical Replay gates are not opened by this module.
"""
from __future__ import annotations

from dataclasses import asdict, dataclass, replace

from .errors import Unavailable, Unsupported, ValidationError
from .mechanics import fee_components
from .model import Bin, FunctionType, PoolState
from .swap_fees import RecipientFees, allocate_recipients
from .swap_math import BinQuote
from .swap_quote import BitmapExtension, PoolQuote, SwapIntent, SwapMode, quote_swap

PROGRAM_SHA256 = 'd296c6771cec945601027613ca637c1be6721044c5859009d41c453477844c1f'


def _checked(value: int, bits: int, name: str) -> int:
    if type(value) is not int or not 0 <= value < (1 << bits):
        raise ValidationError(f'{name} overflows u{bits}')
    return value


@dataclass(frozen=True, slots=True)
class BinTransition:
    bin_id: int
    quote: BinQuote
    fee_token: str
    recipient_fees: RecipientFees
    rounding_protocol_fee: int
    unallocated_output_surplus: int
    mm_base_fee: int
    mm_variable_fee: int
    post_bin: Bin
    input_conservation_residual: int
    output_conservation_residual: int

    @property
    def protocol_fee(self) -> int:
        return self.recipient_fees.protocol_fee + self.rounding_protocol_fee


@dataclass(frozen=True, slots=True)
class SwapTransition:
    intent: SwapIntent
    quote: PoolQuote
    post_state: PoolState
    fills: tuple[BinTransition, ...]
    amount_in: int
    amount_out: int
    amount_left: int
    mm_fee: int
    limit_order_fee: int
    protocol_fee: int
    host_fee: int
    base_trading_fee: int
    rounding_protocol_fee: int
    unallocated_output_surplus: int
    fee_token: str
    output_token: str
    start_bin: int
    end_bin: int
    fee_bps: int
    binary_sha256: str = PROGRAM_SHA256
    historical_prestate_validated: bool = False
    historical_runtime_feature_parity: str = 'UNVERIFIED'

    def event_amounts(self) -> dict:
        """Comparable Swap2Evt economics, including exact-out input-cap left."""
        return {
            'start_bin_id': self.start_bin, 'end_bin_id': self.end_bin,
            'amount_in': self.amount_in, 'amount_out': self.amount_out,
            'amount_left': self.amount_left, 'swap_for_y': self.intent.swap_for_y,
            'fee_bps': self.fee_bps, 'mm_fee': self.mm_fee,
            'limit_order_fee': self.limit_order_fee, 'protocol_fee': self.protocol_fee,
            'host_fee': self.host_fee,
            'fees_on_input': self.quote.fills[0].quote.fee_on_input,
            'fees_on_token_x': self.fee_token == 'x',
        }

    def summary(self) -> dict:
        return {
            **self.event_amounts(), 'base_trading_fee': self.base_trading_fee,
            'rounding_protocol_fee': self.rounding_protocol_fee,
            'unallocated_output_surplus': self.unallocated_output_surplus,
            'fee_token': self.fee_token, 'output_token': self.output_token,
            'sdk_fee_scalar': self.quote.sdk_fee,
            'sdk_protocol_fee_scalar': self.quote.sdk_protocol_fee,
            'binary_sha256': self.binary_sha256,
            'source_economic_hash': self.quote.reference.source_economic_hash,
            'post_economic_hash': self.post_state.economic_hash(),
            'historical_prestate_validated': False,
            'historical_runtime_feature_parity': self.historical_runtime_feature_parity,
            'fills': [asdict(fill) for fill in self.fills],
        }


def _apply_bin(source: Bin, quote: BinQuote, *, protocol_share: int,
               host_present: bool, fee_token: str,
               base_rate: int, variable_rate: int) -> BinTransition:
    if not source.limit_order_fields_complete:
        raise Unavailable('LO transition requires all preserved Bin state fields')
    if source.bin_id != quote.bin_id or source.price <= 0:
        raise ValidationError('bin quote does not identify a priced source bin')
    fees = allocate_recipients(quote.fee_split, protocol_share=protocol_share,
                               host_present=host_present)
    post = replace(source)
    mm, processed, opened = quote.layers
    if (mm.source, processed.source, opened.source) != ('MM', 'PROCESSED_LO', 'OPEN_LO'):
        raise ValidationError('unexpected fill-layer ordering')
    incoming, outgoing = ('amount_x', 'amount_y') if quote.swap_for_y else ('amount_y', 'amount_x')
    setattr(post, incoming, _checked(getattr(post, incoming) + mm.net_amount_in, 64, incoming))
    setattr(post, outgoing, _checked(getattr(post, outgoing) - mm.gross_amount_out, 64, outgoing))
    post.processed_order_remaining_amount = _checked(
        post.processed_order_remaining_amount - processed.gross_amount_out, 64,
        'processed order remaining amount')
    if opened.gross_amount_out:
        if post.processed_order_remaining_amount:
            raise ValidationError('open cohort filled before processing previous cohort')
        post.total_processing_order_amount = source.open_order_amount
        post.processed_order_remaining_amount = _checked(
            source.open_order_amount - opened.gross_amount_out, 64,
            'new processing cohort remaining amount')
        post.open_order_amount = 0
        post.order_age = _checked(source.order_age + 1, 32, 'order age')
    lo_out = processed.gross_amount_out + opened.gross_amount_out
    fulfilled_key = 'fulfilled_order_amount_y' if quote.swap_for_y else 'fulfilled_order_amount_x'
    lo_fee_key = 'limit_order_fee_bid_side' if quote.swap_for_y else 'limit_order_fee_ask_side'
    setattr(post, fulfilled_key, _checked(getattr(post, fulfilled_key) + lo_out, 64, fulfilled_key))
    setattr(post, lo_fee_key, _checked(getattr(post, lo_fee_key) + fees.limit_order_fee, 64, lo_fee_key))
    if fees.mm_lp_fee:
        # The deployed program floors scaled liquidity BEFORE division. Using
        # fee*Q128/full_supply differs for fractional Q64 liquidity shares.
        scaled_supply = source.liquidity_supply >> 64
        if not scaled_supply:
            raise ValidationError('MM fee cannot accrue to zero scaled liquidity')
        fee_growth = (fees.mm_lp_fee << 64) // scaled_supply
        stored_key = 'fee_x_stored' if fee_token == 'x' else 'fee_y_stored'
        setattr(post, stored_key, _checked(getattr(post, stored_key) + fee_growth, 128, stored_key))
    # Actual d296 binary behavior differs from the pinned SDK protocol scalar:
    # output-fee mode assigns EVERY positive exact-out delta to protocol;
    # input-fee mode leaves the output delta as unassigned vault surplus.
    rounding_protocol = quote.rounding_output_delta if not quote.fee_on_input else 0
    surplus = quote.rounding_output_delta - rounding_protocol
    _checked(fees.protocol_fee + rounding_protocol, 64, 'protocol fee')
    input_fee = fees.trading_fee if quote.fee_on_input else 0
    output_fee = fees.trading_fee + rounding_protocol if not quote.fee_on_input else 0
    input_residual = quote.net_amount_in + input_fee - quote.amount_in
    output_residual = quote.gross_amount_out - quote.amount_out - output_fee - surplus
    if input_residual or output_residual:
        raise ValidationError('model swap token conservation failed')
    mm_parts = fee_components(quote.fee_split.mm_fee, base_rate, variable_rate, protocol_share)
    if mm_parts['lp_base'] + mm_parts['lp_variable'] != fees.mm_lp_fee:
        raise ValidationError('MM analytical fee attribution changed participant allocation')
    post.validate()
    return BinTransition(source.bin_id, quote, fee_token, fees, rounding_protocol, surplus,
                         mm_parts['lp_base'], mm_parts['lp_variable'], post,
                         input_residual, output_residual)


def simulate_swap(source: PoolState, intent: SwapIntent, timestamp: int, *,
                  slot: int | None = None, bitmap_extension: BitmapExtension | None = None,
                  extension_known: bool = False, max_bin_visits: int = 100000) -> SwapTransition:
    """Compute a pure LO transition without changing caller-owned state.

    Host presence changes recipient allocation, not the amount-quote inputs.
    The amount-only SDK quote is explicitly generated with host absent, then
    the actual intent's host flag is used for every per-bin recipient split.
    This API does not attach factual prestate or historical validation status.
    """
    source.validate()
    if source.effective_function_type != FunctionType.LIMIT_ORDER:
        raise Unsupported('new transition model is scoped to effective LIMIT_ORDER pools')
    if source.binary_sha256 is not None and source.binary_sha256 != PROGRAM_SHA256:
        raise Unsupported('transition model is not bound to this deployed binary')
    if source.data_kind == 'HISTORICAL' and source.binary_sha256 is None:
        raise Unavailable('historical transition input lacks the validated program binary binding')
    if source.protocol_fee_x is None or source.protocol_fee_y is None:
        raise Unavailable('protocol-counter prestate is not represented')
    if not isinstance(intent, SwapIntent):
        raise ValidationError('transition requires a typed actual SwapIntent')
    quote = quote_swap(source, replace(intent, host_fee_present=False), timestamp, slot=slot,
                       bitmap_extension=bitmap_extension, extension_known=extension_known,
                       max_bin_visits=max_bin_visits)
    if not quote.amount_out:
        raise ValidationError('program rejects zero-output swaps')
    state = replace(source, parameters=replace(source.parameters), variable=replace(source.variable),
                    bins={i: replace(bin) for i, bin in source.bins.items()},
                    known_bin_arrays=list(source.known_bin_arrays), slot=quote.reference.slot)
    transitions = []
    changed_arrays = set()
    for fill in quote.fills:
        changed = _apply_bin(state.bins[fill.quote.bin_id], fill.quote,
                             protocol_share=state.parameters.protocol_share,
                             host_present=intent.host_fee_present, fee_token=quote.fee_token,
                             base_rate=fill.base_rate, variable_rate=fill.variable_rate)
        state.bins[changed.bin_id] = changed.post_bin
        counter = 'protocol_fee_x' if quote.fee_token == 'x' else 'protocol_fee_y'
        setattr(state, counter, _checked(getattr(state, counter) + changed.protocol_fee, 64, counter))
        transitions.append(changed)
        changed_arrays.add(changed.bin_id // 70)
    words = list(state.bin_array_bitmap)
    for index in changed_arrays:
        bins = [state.bins[i] for i in range(index * 70, index * 70 + 70)]
        if any(not bin.limit_order_fields_complete for bin in bins):
            raise Unavailable('bitmap mutation needs complete array liquidity evidence')
        remains = any(bin.amount_x or bin.amount_y or bin.open_order_amount
                      or bin.processed_order_remaining_amount for bin in bins)
        if not remains:
            if not -512 <= index <= 511:
                raise Unsupported('external-bitmap depletion mutation is not yet program-validated')
            word, bit = divmod(index + 512, 64)
            words[word] &= ~(1 << bit)
    state.bin_array_bitmap = tuple(words)
    state.active_id = quote.end_bin
    state.variable.index_reference = quote.reference.index_reference
    state.variable.volatility_reference = quote.reference.volatility_reference
    state.variable.volatility_accumulator = quote.reference.final_quote_volatility_accumulator
    # Actual d296 updates this timestamp only when the active bin changes.
    # Same-bin swaps can change index/volatility references and accumulator
    # without updating it; crossing also updates it with zero fees or a
    # saturated accumulator. Dedicated SBF cases distinguish those guards.
    if quote.end_bin != source.active_id:
        state.variable.last_update_timestamp = timestamp
    state.validate()
    cap = intent.amount_in if intent.mode == SwapMode.EXACT_IN else intent.max_in_amount
    return SwapTransition(
        intent, quote, state, tuple(transitions), quote.amount_in, quote.amount_out,
        cap - quote.amount_in,
        sum(fill.recipient_fees.mm_lp_fee for fill in transitions),
        sum(fill.recipient_fees.limit_order_fee for fill in transitions),
        sum(fill.protocol_fee for fill in transitions),
        sum(fill.recipient_fees.host_fee for fill in transitions),
        quote.trading_fee, sum(fill.rounding_protocol_fee for fill in transitions),
        sum(fill.unallocated_output_surplus for fill in transitions), quote.fee_token,
        quote.output_token, quote.start_bin, quote.end_bin, quote.fills[-1].total_rate)
